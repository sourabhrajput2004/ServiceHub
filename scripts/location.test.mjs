import assert from 'node:assert/strict';
import {coordinates,distanceKm,nearestShops,SERVICE_AREAS,locationOptions,findLocations} from '../src/utils/nearbyShops.js';
assert.equal(distanceKm({lat:0,lng:0},{lat:0,lng:0}),0);
assert.ok(Math.abs(distanceKm({lat:0,lng:0},{lat:0,lng:1})-111.195)<.01);
assert.equal(coordinates({lat:null,lng:1}),null);
assert.equal(coordinates({lat:91,lng:20}),null);
assert.equal(coordinates({lat:28,lng:''}),null);
assert.equal(distanceKm({lat:28,lng:77},null),null);
const shops=[{id:'far',coordinates:{lat:28.7,lng:77.4}},{id:'unknown'},{id:'near',coordinates:{lat:28.64,lng:77.37}},{id:'same',coordinates:{lat:28.64,lng:77.37}}];
const sorted=nearestShops(shops,{lat:28.64,lng:77.37});
assert.deepEqual(sorted.map(s=>s.id),['near','same','far','unknown']);
assert.equal(sorted.at(-1).distanceKm,null);
assert.deepEqual(shops.map(s=>s.id),['far','unknown','near','same']);
assert.deepEqual(nearestShops(shops,null).map(s=>s.id),shops.map(s=>s.id));
assert.ok(nearestShops(shops,null).every(s=>s.distanceKm===null));
const options=locationOptions([{id:'one',shopName:'Local shop',locality:'Indirapuram, Ghaziabad',address:'Shop 14, Sample market',coordinates:{lat:28.64,lng:77.37}}]);
assert.ok(findLocations('vaishali ghaziabad',options).some(o=>o.id==='vaishali'));
assert.ok(findLocations('  RAJ NAGAR  ',options).some(o=>o.id==='raj-nagar'));
assert.ok(findLocations('\u0935\u0948\u0936\u093e\u0932\u0940',options).some(o=>o.id==='vaishali'));
assert.ok(findLocations('Sample market',options).some(o=>o.key==='shop:one'));
assert.equal(findLocations('does not exist',options).length,0);
assert.ok(SERVICE_AREAS.every(area=>coordinates(area)));
console.log('Passed distance calculation, nearest-first sorting, missing coordinates, stable order, non-mutation and bilingual location-search checks.');
